let currentLang = 'ar';

function t(key, vars = {}) {
  let text = (translations[currentLang] || translations.ar)[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    text = text.replace(`{${k}}`, v);
  }
  return text;
}

function setLanguage(lang) {
  currentLang = lang;
  const body = document.body;
  body.classList.remove('lang-ar', 'lang-en', 'lang-fa');
  body.classList.add(`lang-${lang}`);
  body.dir = (lang === 'ar' || lang === 'fa') ? 'rtl' : 'ltr';
  if (lang === 'fa') body.dir = 'rtl';
  if (lang === 'en') body.dir = 'ltr';
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang][key]) {
      el.textContent = translations[currentLang][key];
    }
  });
}

function tWithLang(key, lang, vars = {}) {
  let text = (translations[lang] || translations.ar)[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    text = text.replace(`{${k}}`, v);
  }
  return text;
}

function getSelectionMethodName(method) {
  const map = {
    tournament: t('tournamentMethod'),
    roulette: t('rouletteMethod'),
    rank: t('rankMethod')
  };
  return map[method] || method;
}
